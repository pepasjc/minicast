/*
	Generate a computed-goto threaded block interpreter straight from the real
	opcode table: this TU includes sh4_opcode_list.cpp and iterates opcodes[]
	(oph_name carries the handler name, type says whether an op writes PC).
	The handlers referenced by the table are never called here, so they may
	stay unresolved:

	    g++ -O2 -std=gnu++17 -DTARGET_LINUX_x64 -Ilibswirl -Ilibswirl/deps \
	        tools/gen_sh4_block_interp.cpp -o /tmp/gen_bi \
	        -Wl,--unresolved-symbols=ignore-all
	    /tmp/gen_bi libswirl/hw/sh4/interpr/sh4_block_interp.inl

	Emits:
	  - op2insn[0x10000]: 16-bit opcode -> 8-bit index into opcodes[]
	    (SH4_BI_MISS = unknown), filled at runtime from OpDesc[] pointer
	    identity so it inherits the canonical matching/priority rules exactly.
	  - interpret_block(u16* ops): threaded dispatch over pre-decoded opcode
	    words, direct handler calls, break after PC-writing ops.
*/

#include "../libswirl/hw/sh4/sh4_opcode_list.cpp"

#include <cstdio>

int main(int argc, char** argv)
{
	const char* out = argc > 1 ? argv[1] : "libswirl/hw/sh4/interpr/sh4_block_interp.inl";

	// count real entries (the {0,0,...} terminator ends the table)
	size_t n = 0;
	while (opcodes[n].oph_name)
		n++;

	if (n > 255)
	{
		fprintf(stderr, "%zu entries: does not fit an 8-bit map with a reserved miss slot\n", n);
		return 1;
	}

	FILE* o = fopen(out, "w");
	if (!o)
	{
		fprintf(stderr, "cannot open %s for writing\n", out);
		return 1;
	}

	fprintf(o,
		"//\n"
		"// AUTO-GENERATED by tools/gen_sh4_block_interp.cpp from opcodes[]\n"
		"// %zu entries. Do not edit; regenerate instead.\n"
		"//\n"
		"// Include after: types.h, sh4_interpreter.h, sh4_opcode_list.h, sh4_core.h,\n"
		"// interpr/sh4_opcodes.h, reios/reios.h. Requires GCC/Clang (computed goto).\n"
		"//\n"
		"// Contract: `ops` is a pre-decoded run of instruction words for the guest\n"
		"// code at next_pc; it must end with (or contain) a PC-writing instruction,\n"
		"// which is what terminates the loop. next_pc is advanced past each word\n"
		"// before its handler runs, exactly like the canonical interpreter loop, so\n"
		"// PC-relative ops and delay slots (executed by the branch handlers via\n"
		"// ExecuteDelayslot(), which fetches from guest memory) behave identically.\n"
		"// Cycle accounting and interrupt checks are the caller's business, per block.\n"
		"// No sr.FD gate: FPU-disable exceptions are not supported here - don't hand\n"
		"// blocks to this interpreter while sr.FD may be set.\n"
		"\n"
		"#define SH4_BI_NUM_INSNS %zu\n"
		"#define SH4_BI_MISS      255\n"
		"\n"
		"u8 op2insn[0x10000];\n"
		"\n"
		"// Build the 16-bit opcode -> 8-bit insn map. Call after BuildOpcodeTables().\n"
		"// OpDesc[] pointer identity keeps priority and special cases exact;\n"
		"// anything not in opcodes[] (missing_opcode) maps to SH4_BI_MISS.\n"
		"void sh4_block_interp_init()\n"
		"{\n"
		"\textern sh4_opcodelistentry opcodes[];\n"
		"\n"
		"\tfor (u32 op = 0; op < 0x10000; op++)\n"
		"\t{\n"
		"\t\tconst sh4_opcodelistentry* d = OpDesc[op];\n"
		"\n"
		"\t\tif (d >= &opcodes[0] && d < &opcodes[SH4_BI_NUM_INSNS])\n"
		"\t\t\top2insn[op] = (u8)(d - &opcodes[0]);\n"
		"\t\telse\n"
		"\t\t\top2insn[op] = SH4_BI_MISS;\n"
		"\t}\n"
		"}\n"
		"\n"
		"void interpret_block(u16* ops)\n"
		"{\n"
		"\tstatic const void* const bi_dispatch[256] =\n"
		"\t{\n", n, n);

	for (size_t i = 0; i < 256; i += 8)
	{
		fprintf(o, "\t\t");
		for (size_t j = i; j < i + 8; j++)
			if (j < n)
				fprintf(o, "&&bi_%zu, ", j);
			else
				fprintf(o, "&&bi_miss, ");
		fprintf(o, "\n");
	}

	fprintf(o,
		"\t};\n"
		"\n"
		"\tu16 op;\n"
		"\n"
		"// threaded dispatch: every handler tail refetches and jumps through the\n"
		"// table itself, so each opcode gets its own indirect branch (own BTB entry)\n"
		"#define BI_NEXT() op = *ops++; next_pc = next_pc + 2; goto *bi_dispatch[op2insn[op]]\n"
		"\n"
		"\tBI_NEXT();\n"
		"\n");

	for (size_t i = 0; i < n; i++)
	{
		const sh4_opcodelistentry& e = opcodes[i];

		fprintf(o, "bi_%zu:\t// %s\n", i, e.diss ? e.diss : e.oph_name);

		fprintf(o, "\t\t%s(op);\n", e.oph_name);

		if (e.type & WritesPC)
			fprintf(o, "\t\treturn;\n\n");
		else
			fprintf(o, "\t\tBI_NEXT();\n\n");
	}

	fprintf(o,
		"bi_miss:\t// unknown opcode: canonical dispatch raises the exception\n"
		"\t\tOpPtr[op](op);\n"
		"\t\treturn;\n"
		"\n"
		"#undef BI_NEXT\n"
		"}\n");

	fclose(o);
	printf("wrote %s: %zu entries + miss slot\n", out, n);
	return 0;
}
